int getTinggi(int level) {
    if (level == 1) return T1;
    if (level == 2) return T2;
    return T3;
}

// Mengambil lebar labirin berdasarkan level
int getLebar(int level) {
    if (level == 1) return L1;
    if (level == 2) return L2;
    return L3;
}

// Mengambil isi labirin berdasarkan level
char getIsiLabirin(int level, int y, int x) {

    if (y < 0 || y >= getTinggi(level) ||
        x < 0 || x >= getLebar(level)) {
        return '#';
    }

    if (level == 1) {
        return easy[y][x];
    }
    else if (level == 2) {
        return normal[y][x];
    }
    else {
        return hard[y][x];
    }
}

